#######################function for handle numeric
format_numeric_column <- function(x) {
  suppressWarnings(case_when(
    !is.na(as.numeric(x)) ~ 
      formatC(as.numeric(x), digits=2, format="f"), 
    TRUE ~ as.character(x)
  ))
}
