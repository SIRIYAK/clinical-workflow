# function formats numeric columns, 
# rounding them to two decimal places and replacing zero values with an empty string.
format_numbers <- function(df_lb0, cols) {
  df_lb0[, cols] <- lapply(df_lb0[, cols], function(x) {
    if (is.numeric(x)) {
      ifelse(x == 0, "", round(x, 2))  # Round and replace 0 with an empty string
    } else {
      x  # Return as is for non-numeric columns
    }
  })
  return(df_lb0)
}

# Function applies similar logic but is extended to work with both numeric and 
# character columns. In the case of character columns, it specifically handles "0.0" values.
format_numbers_ <- function(df_lb, cols) {
  df_lb[, cols] <- lapply(df_lb[, cols], function(x) {
    if (is.numeric(x) || is.character(x)) {
      ifelse(x == "0.0", "", round(as.numeric(x), 2))  # Handle "0.0" as a character
    } else {
      x  # Return as is for other data types
    }
  })
  return(df_lb)
}

